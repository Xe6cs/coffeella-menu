// Generates supabase/seed.sql from data/menu.v1.snapshot.json.
//
// The seed is idempotent: rows are matched by slug and existing rows are left
// untouched ("on conflict do nothing"), so re-running never duplicates
// products and never overwrites edits made later in the admin panel.
//
// Usage:  node scripts/generate-seed.mjs [--check]

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const snapshotPath = resolve(here, "../data/menu.v1.snapshot.json");
const seedPath = resolve(here, "../supabase/seed.sql");
const checkOnly = process.argv.includes("--check");

const snapshot = JSON.parse(readFileSync(snapshotPath, "utf8"));

const lit = (v) => (v === null || v === undefined ? "null" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const row = (values) => `  (${values.map(lit).join(", ")})`;

const categories = snapshot.categories;
const groups = categories.flatMap((c) => c.groups.map((g) => ({ ...g, category_slug: c.slug })));
const products = groups.flatMap((g) => g.products.map((p) => ({ ...p, group_slug: g.slug })));

const sql = `-- Generated by scripts/generate-seed.mjs from data/menu.v1.snapshot.json
-- Source: ${snapshot.source} (sha256 ${snapshot.sourceSha256})
-- Expected counts: ${snapshot.counts.categories} categories, ${snapshot.counts.groups} groups, ${snapshot.counts.products} products.
-- Idempotent: existing rows (matched by slug) are never modified or duplicated.

insert into public.categories (slug, name_ar, name_en, icon, photo_path, photo_focus, sort_order) values
${categories.map((c) => row([c.slug, c.name_ar, c.name_en, c.icon, c.photo, c.photo_focus, c.sort_order])).join(",\n")}
on conflict (slug) do nothing;

insert into public.product_groups (category_id, slug, name_ar, name_en, sort_order)
select c.id, v.slug, v.name_ar, v.name_en, v.sort_order
from (values
${groups.map((g) => row([g.category_slug, g.slug, g.name_ar, g.name_en, g.sort_order])).join(",\n")}
) as v (category_slug, slug, name_ar, name_en, sort_order)
join public.categories c on c.slug = v.category_slug
on conflict (slug) do nothing;

insert into public.products (group_id, slug, name_ar, name_en, price_min, price_max, sort_order)
select g.id, v.slug, v.name_ar, v.name_en, v.price_min, v.price_max::integer, v.sort_order
from (values
${products.map((p) => row([p.group_slug, p.slug, p.name_ar, p.name_en, p.price_min, p.price_max, p.sort_order])).join(",\n")}
) as v (group_slug, slug, name_ar, name_en, price_min, price_max, sort_order)
join public.product_groups g on g.slug = v.group_slug
on conflict (slug) do nothing;
`;

if (checkOnly) {
  if (!existsSync(seedPath) || readFileSync(seedPath, "utf8") !== sql) {
    console.error("supabase/seed.sql is out of date with the snapshot");
    process.exit(1);
  }
  console.log("seed.sql up to date");
} else {
  writeFileSync(seedPath, sql);
  console.log(`Wrote ${seedPath} (${categories.length} categories, ${groups.length} groups, ${products.length} products)`);
}
